from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from sse_starlette.sse import EventSourceResponse
from dotenv import load_dotenv
import asyncio
import json
import os

load_dotenv()

# Import our compiled LangGraph swarm
from swarm import chrono_swarm, SwarmState

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/trigger-swarm")
async def trigger_swarm(vessel_id: str = "MSC_VANESSA_9703291"):
    """
    This endpoint uses SSE to stream the LangGraph execution live to the frontend.
    """
    initial_state: SwarmState = {
        "vessel_id": vessel_id,
        "declared_displacement": 129500,
        "optical_analysis": "",
        "acoustic_analysis": "",
        "legal_verdict": "",
        "final_action": "",
        "fraud_detected": False,
        "live_logs": []
    }

    async def event_generator():
        # Stream the initial connection
        yield {"data": json.dumps({"agent": "System", "message": f"Geofence breach detected. Vessel {vessel_id} entering port limits. Waking swarm..."})}
        await asyncio.sleep(1)

        # Run the LangGraph step-by-step
        for output in chrono_swarm.stream(initial_state):
            # The output is a dict where the key is the node name that just ran
            for node_name, state_update in output.items():
                # Extract the latest log generated by that specific agent
                latest_log = state_update["live_logs"][-1]
                
                # Yield the data to the frontend immediately
                yield {"data": json.dumps({"agent": node_name, "message": latest_log, "state": state_update})}
                await asyncio.sleep(1.5) # Artificial delay for dramatic UI effect

        yield {"data": json.dumps({"agent": "System", "message": "Swarm execution complete. Connection closed.", "done": True})}

    return EventSourceResponse(event_generator())